function cloneClassroom(room: Classroom): Classroom {
  return {
    ...room,
    equipment: room.equipment.map((item) => ({ ...item })),
    facilities: [...room.facilities],
    currentLecture: room.currentLecture ? { ...room.currentLecture } : undefined,
  };
}

